// 日付ごとに1つのTipを決定的に選ぶ（全員が同じ日は同じTipを見る）。
// Math.random()は使わず、日数を配列長で割った余りで巡回させる。
export function getTodaysTip(date: Date = new Date()): DailyTip {
  const dayIndex = Math.floor(date.getTime() / 86_400_000);
  const index = ((dayIndex % DAILY_TIPS.length) + DAILY_TIPS.length) % DAILY_TIPS.length;
  return DAILY_TIPS[index];
}
